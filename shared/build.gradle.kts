// Code shared by the Android app (:app) and the iOS app (iosApp/): models, validation, the ViewModel and
// every Compose screen. Platform pieces live in androidMain / iosMain; the Android Firebase backend stays in :app.
plugins {
  alias(libs.plugins.kotlin.multiplatform)
  alias(libs.plugins.kotlin.compose)
  alias(libs.plugins.compose.multiplatform)
  alias(libs.plugins.android.kotlin.multiplatform.library)
}

// Build-time constants for shared code, from gradle.properties (the same `rsetsparks.blaze` switch Android uses).
val generateSharedBuildConfig by tasks.registering {
  val blaze = providers.gradleProperty("rsetsparks.blaze").orElse("false")
  val outputDir = layout.buildDirectory.dir("generated/sharedBuildConfig/kotlin")
  inputs.property("blaze", blaze)
  outputs.dir(outputDir)
  doLast {
    val file = outputDir.get().file("com/example/SharedBuildConfig.kt").asFile
    file.parentFile.mkdirs()
    file.writeText(
      """
      |package com.example
      |
      |/** Generated by shared/build.gradle.kts from gradle.properties. */
      |object SharedBuildConfig {
      |    /** Firebase project is on Blaze: photo uploads and push notifications are available. */
      |    const val BLAZE: Boolean = ${blaze.get().toBoolean()}
      |}
      |""".trimMargin()
    )
  }
}

